/**
 * Late Interaction skip policy.
 *
 * Embedding indexes EVERYTHING (HNSW recall is precious — we want even the
 * vendored/generated chunks to be findable for full-text + embedding search).
 * But the late-interaction reranker is the slow phase, and it adds value only
 * on chunks a human would actually want to read. So we filter the chunk list
 * BEFORE the LI encoder sees it.
 *
 * Filters (any match → skip):
 *   1. Path-based: vendored / build-output / dependency-cache directories
 *   2. Pattern-based: minified files, source maps, lock files
 *   3. Generated-content marker: leading "// @generated", "// Code generated by",
 *      or "DO NOT EDIT" markers in chunk text
 *   4. Per-file token budget: skip files whose total chunk tokens exceed N
 *      (huge auto-generated files like grammar tables, JSON dumps)
 *
 * Configurable via:
 *   - SWEET_SEARCH_LI_SKIP_DISABLE=1     → disable all skip policy (LI everything)
 *   - SWEET_SEARCH_LI_SKIP_FILE=<path>   → load extra patterns from a file
 *                                          (one regex per line, # comments allowed)
 *   - SWEET_SEARCH_LI_MAX_FILE_TOKENS=N  → per-file token cap (default: 50_000)
 *
 * The policy is intentionally CONSERVATIVE — it skips the obviously-junk files
 * everyone agrees on. Tune via the override file for project-specific cases.
 */

import { existsSync, readFileSync } from 'fs';

/**
 * Default directory exclusions matched as path SEGMENTS (so `node_modules`
 * matches `src/node_modules/...` but `mynode_modules.js` does not).
 *
 * NOTE: kept short on purpose. Project-specific dirs go in the override file.
 */
const DEFAULT_DIR_EXCLUDES = [
  'node_modules',
  'vendor',
  'third_party',
  'thirdparty',
  'bower_components',
  'jspm_packages',
  '.git',
  'dist',
  'build',
  'out',
  'target',           // Rust + Java
  '.next',            // Next.js
  '.nuxt',            // Nuxt
  '.svelte-kit',      // SvelteKit
  '.turbo',           // Turborepo cache
  '.cache',           // Generic cache
  '__pycache__',      // Python bytecode
  '.venv',            // Python venv
  'venv',
  '.tox',
  'coverage',         // Coverage reports
  '.coverage',
  '.pytest_cache',
  '.mypy_cache',
  '.gradle',
  '.idea',            // JetBrains
  '.vscode',
];

/**
 * Default filename/extension patterns matched against the BASENAME (last
 * path segment). Each entry is a regex that's compiled lazily on first use.
 */
const DEFAULT_BASENAME_PATTERNS = [
  /\.min\.(js|css|mjs|cjs)$/i,
  /\.bundle\.(js|css)$/i,
  /\.umd\.js$/i,
  /\.iife\.js$/i,
  /\.map$/i,                                  // source maps
  /^package-lock\.json$/i,
  /^pnpm-lock\.yaml$/i,
  /^yarn\.lock$/i,
  /^Cargo\.lock$/i,
  /^Gemfile\.lock$/i,
  /^composer\.lock$/i,
  /^poetry\.lock$/i,
  /^Pipfile\.lock$/i,
  /^go\.sum$/i,
  /\.lock$/i,                                 // catch-all for *.lock
  /\.snap$/i,                                 // jest snapshots
];

/**
 * Markers that indicate a file is auto-generated. We only check the FIRST
 * ~500 characters of a chunk's text since real generated headers always
 * appear at the top.
 */
const GENERATED_MARKERS = [
  '@generated',
  'Code generated by',
  'DO NOT EDIT',
  'AUTO-GENERATED FILE',
  'AUTOGENERATED FILE',
  'This file is automatically generated',
];

const DEFAULT_MAX_FILE_TOKENS = 50_000;

let _cachedExtraPatterns = null;
function loadExtraPatternsFromFile() {
  if (_cachedExtraPatterns !== null) return _cachedExtraPatterns;
  const path = process.env.SWEET_SEARCH_LI_SKIP_FILE;
  if (!path || !existsSync(path)) {
    _cachedExtraPatterns = [];
    return _cachedExtraPatterns;
  }
  try {
    const lines = readFileSync(path, 'utf8').split(/\r?\n/);
    _cachedExtraPatterns = lines
      .map((l) => l.trim())
      .filter((l) => l && !l.startsWith('#'))
      .map((l) => {
        try { return new RegExp(l); } catch { return null; }
      })
      .filter((r) => r !== null);
  } catch {
    _cachedExtraPatterns = [];
  }
  return _cachedExtraPatterns;
}

/**
 * Check if a file path matches any of the default directory excludes
 * (matched as path segments).
 */
export function pathHasExcludedDir(filePath) {
  if (!filePath) return false;
  const segments = filePath.split(/[/\\]/);
  for (const seg of segments) {
    if (DEFAULT_DIR_EXCLUDES.includes(seg)) return true;
  }
  return false;
}

/**
 * Check if a file's basename matches any of the default skip patterns
 * or any extra pattern loaded from SWEET_SEARCH_LI_SKIP_FILE.
 */
export function basenameMatchesSkipPattern(filePath) {
  if (!filePath) return false;
  const idx = Math.max(filePath.lastIndexOf('/'), filePath.lastIndexOf('\\'));
  const basename = idx >= 0 ? filePath.slice(idx + 1) : filePath;
  for (const re of DEFAULT_BASENAME_PATTERNS) {
    if (re.test(basename)) return true;
  }
  // Also try the extra patterns against the FULL path (so users can write
  // either path-substring patterns or basename patterns).
  const extras = loadExtraPatternsFromFile();
  for (const re of extras) {
    if (re.test(filePath) || re.test(basename)) return true;
  }
  return false;
}

/**
 * Check if a chunk's text starts with a generated-file marker.
 * Only inspects the first ~500 chars (these markers always appear at the top).
 */
export function chunkLooksGenerated(text) {
  if (!text) return false;
  const head = text.slice(0, 500);
  for (const marker of GENERATED_MARKERS) {
    if (head.includes(marker)) return true;
  }
  return false;
}

/**
 * Filter a chunk list down to those eligible for late-interaction encoding.
 *
 * @param {Array<{file: string, text?: string, content?: string}>} chunks
 * @returns {{ kept: Array, skipped: Array, stats: object }}
 */
export function applyLiSkipPolicy(chunks) {
  if (process.env.SWEET_SEARCH_LI_SKIP_DISABLE === '1' || !Array.isArray(chunks)) {
    return { kept: chunks || [], skipped: [], stats: emptyStats() };
  }

  const maxFileTokens = parseInt(process.env.SWEET_SEARCH_LI_MAX_FILE_TOKENS || '', 10) > 0
    ? parseInt(process.env.SWEET_SEARCH_LI_MAX_FILE_TOKENS, 10)
    : DEFAULT_MAX_FILE_TOKENS;

  // First pass: per-file token totals + per-chunk reasons.
  const fileTokenTotal = new Map();
  const fileFirstReason = new Map(); // file → reason ('dir', 'pattern', 'generated', 'huge', null)

  for (const chunk of chunks) {
    if (!chunk?.file) continue;
    if (fileFirstReason.has(chunk.file)) continue; // already classified

    let reason = null;
    if (pathHasExcludedDir(chunk.file)) reason = 'dir';
    else if (basenameMatchesSkipPattern(chunk.file)) reason = 'pattern';
    else {
      const text = chunk.text || chunk.content || '';
      if (chunkLooksGenerated(text)) reason = 'generated';
    }
    fileFirstReason.set(chunk.file, reason);
  }

  // Per-file token totals (only for files not already classified for skip)
  for (const chunk of chunks) {
    if (!chunk?.file) continue;
    if (fileFirstReason.get(chunk.file)) continue; // already skipped
    const text = chunk.text || chunk.content || '';
    // Use cheap char/4 estimate; we don't need exact tokenization here
    const est = Math.ceil(text.length / 4);
    fileTokenTotal.set(chunk.file, (fileTokenTotal.get(chunk.file) || 0) + est);
  }
  for (const [file, total] of fileTokenTotal) {
    if (total > maxFileTokens) fileFirstReason.set(file, 'huge');
  }

  // Second pass: split chunks into kept/skipped buckets using the file decisions.
  const kept = [];
  const skipped = [];
  const stats = emptyStats();
  for (const chunk of chunks) {
    const reason = chunk?.file ? fileFirstReason.get(chunk.file) : null;
    if (reason) {
      skipped.push(chunk);
      stats[reason]++;
      stats.totalSkipped++;
    } else {
      kept.push(chunk);
    }
  }
  // Distinct file counts (helpful for the summary line)
  stats.skippedFiles = new Set(skipped.map((c) => c.file).filter(Boolean)).size;
  stats.keptFiles = new Set(kept.map((c) => c.file).filter(Boolean)).size;
  return { kept, skipped, stats };
}

function emptyStats() {
  return {
    dir: 0,
    pattern: 0,
    generated: 0,
    huge: 0,
    totalSkipped: 0,
    skippedFiles: 0,
    keptFiles: 0,
  };
}

// Exported for tests
export const _internals = {
  DEFAULT_DIR_EXCLUDES,
  DEFAULT_BASENAME_PATTERNS,
  GENERATED_MARKERS,
  DEFAULT_MAX_FILE_TOKENS,
};
