/**
 * Phase 7 — build the frozen in-distribution probe tiers from the per-language pools.
 *
 * Deterministic + reproducible: reads core/prompt-optimization/data/probe-pools/*.json
 * (10 in-distribution languages, 95 probes), runs the seed-42 stratifiedSplit (§5.0),
 * then PINS the 7 trick probes (4 pathology §5.5 + 3 distractor §5.6) into the dev
 * tier via same-language swaps so GEPA trains on the pathologies (§5.1/§5.5 require
 * trick probes in DEV; the pure random split scatters them). Writes:
 *   - data/p7-dev-probes.json            (40)
 *   - data/frozen/p7-heldout-probes.json (30)
 *   - data/frozen/p7-vault-probes.json   (25)
 *
 * The pin is a deterministic post-process here (stable iteration + first-match swap).
 * TODO(reproducibility): fold a `pinTrickToDev` option into stratifiedSplit so the pin
 * lives in the tested tool rather than this generator (review carry-along item).
 *
 * Run: node core/prompt-optimization/sweep/build-prereg-probes.mjs
 * Plan refs: docs/PHASE7.md §5.0, §5.1, §5.2, §5.5, §5.6, §5.8.
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { stratifiedSplit, validate } from './author-probes.mjs';

const DATA = new URL('../data/', import.meta.url);
const POOLS = new URL('probe-pools/', DATA);
const FROZEN = new URL('frozen/', DATA);
const VAULT_MAP = { javascript:3, typescript:3, go:3, python:3, rust:3, java:2, cpp:2, csharp:2, ruby:2, kotlin:2 };

const isTrick = (p) => Boolean(p.pathology || p.distractor);

export function buildTiers() {
  const files = readdirSync(POOLS).filter((f) => f.endsWith('.json')).sort();
  const all = [];
  for (const f of files) {
    const raw = JSON.parse(readFileSync(new URL(f, POOLS), 'utf8'));
    all.push(...(Array.isArray(raw) ? raw : (raw.probes ?? [])));
  }
  const v = validate(all);
  if (!v.ok) { throw new Error(`probe validation failed: ${v.errors.slice(0, 5).map((e) => `[${e.index}] ${e.message}`).join('; ')}`); }

  const split = stratifiedSplit({ probes: all, seed: 42, perLanguage: { dev: 4, heldout: 3, vault: VAULT_MAP } });
  const dev = [...split.dev], heldout = [...split.heldout], vault = [...split.vault];

  // Pin trick probes into dev (deterministic: stable probe order + first same-language non-trick swap).
  for (const t of all.filter(isTrick)) {
    if (dev.includes(t)) continue;
    const src = heldout.includes(t) ? heldout : vault;
    const swapOut = dev.find((d) => d.language === t.language && !isTrick(d));
    if (!swapOut) throw new Error(`no same-language non-trick dev probe to swap for ${t.id} (${t.language})`);
    src.splice(src.indexOf(t), 1);
    dev.splice(dev.indexOf(swapOut), 1);
    dev.push(t);
    src.push(swapOut);
  }

  // Invariants
  const assert = (c, m) => { if (!c) throw new Error(`invariant failed: ${m}`); };
  assert(dev.length === 40, `dev=${dev.length}≠40`);
  assert(heldout.length === 30, `heldout=${heldout.length}≠30`);
  assert(vault.length === 25, `vault=${vault.length}≠25`);
  assert(dev.filter(isTrick).length === 7, `dev trick=${dev.filter(isTrick).length}≠7`);
  const ids = new Set(all.map((p) => p.id));
  assert(ids.size === 95, `duplicate/again ids: ${ids.size}≠95`);

  return { dev, heldout, vault };
}

const _thisFile = fileURLToPath(import.meta.url);
if (process.argv[1] === _thisFile) {
  const { dev, heldout, vault } = buildTiers();
  mkdirSync(FROZEN, { recursive: true });
  const wrap = (tier, probes) => ({
    _note: `Phase 7 ${tier} tier — generated by build-prereg-probes.mjs from data/probe-pools/ via seed-42 stratifiedSplit + trick-pinned-to-dev (§5.0/§5.1/§5.5). Regenerate, do not hand-edit.`,
    probes,
  });
  writeFileSync(new URL('p7-dev-probes.json', DATA), JSON.stringify(wrap('dev', dev), null, 2) + '\n');
  writeFileSync(new URL('p7-heldout-probes.json', FROZEN), JSON.stringify(wrap('held-out', heldout), null, 2) + '\n');
  writeFileSync(new URL('p7-vault-probes.json', FROZEN), JSON.stringify(wrap('vault', vault), null, 2) + '\n');
  const lang = (arr) => Object.entries(arr.reduce((m, p) => ((m[p.language] = (m[p.language] || 0) + 1), m), {})).sort().map(([k, n]) => `${k}:${n}`).join(' ');
  console.log(`dev=${dev.length} (trick=${dev.filter(isTrick).length}) heldout=${heldout.length} vault=${vault.length}`);
  console.log('dev by-lang:    ', lang(dev));
  console.log('heldout by-lang:', lang(heldout));
  console.log('vault by-lang:  ', lang(vault));
  console.log('wrote: data/p7-dev-probes.json, data/frozen/p7-heldout-probes.json, data/frozen/p7-vault-probes.json');
}
