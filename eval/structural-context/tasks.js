const TASKS = [...BASE_TASKS, ...FRESH_STRUCTURAL_CONTEXT_TASKS];

export function loadStructuralTasks({ splitIds = null, repos = null } = {}) {
  const repoSet = repos?.length ? new Set(repos) : null;
  const idSet = splitIds?.length ? new Set(splitIds) : null;
  return TASKS.filter(t => (!repoSet || repoSet.has(t.repo)) && (!idSet || idSet.has(t.id)));
}

export function listStructuralRepos() {
  return [...new Set(TASKS.map(t => t.repo))].sort();
}

export { TASKS as STRUCTURAL_CONTEXT_TASKS };
