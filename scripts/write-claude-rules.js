/**
 * Claude Code's canonical sweet-search policy lives in the unscoped project
 * rule `.claude/rules/sweet-search.md`.
 *
 * Claude Code auto-loads unscoped `.claude/rules/*.md` files at launch with
 * the same instruction priority as `.claude/CLAUDE.md`; no CLAUDE.md import is
 * required. Keeping the policy here lets `sweet-search init` leave a project's
 * CLAUDE.md completely untouched.
 *
 * Apart from the ownership comment (which Claude strips before injection), the
 * file is the selected shipped policy body verbatim. There is no second,
 * hand-authored Claude-specific decision tree that can contradict it.
 */

import {
  existsSync,
  mkdirSync,
  readFileSync,
  rmdirSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { getPolicyBody } from './inject-agent-instructions.js';

export const CLAUDE_RULES_REL = '.claude/rules/sweet-search.md';

// Block-level HTML comments are removed before Claude injects project rules,
// so ownership metadata consumes no prompt tokens and does not alter M±.
const SENTINEL = '<!-- generated by `sweet-search init`; removed by `sweet-search uninstall` -->';
const LEGACY_SENTINEL =
  '<!-- generated by `sweet-search init`; edit `AGENTS.md` for the canonical policy -->';

function buildBody(variant = 'cli') {
  return `${SENTINEL}\n${getPolicyBody(variant).trimEnd()}\n`;
}

function isOwned(text) {
  return text.includes(SENTINEL) || text.includes(LEGACY_SENTINEL);
}

/**
 * Write `.claude/rules/sweet-search.md`. Idempotent: re-running with
 * unchanged content is a no-op (no mtime bump).
 *
 * @returns 'created' | 'updated' | 'unchanged' | 'preserved-user-file'
 */
export function writeClaudeRules({ projectRoot, variant = 'cli' } = {}) {
  if (!projectRoot) throw new TypeError('write-claude-rules: projectRoot is required');
  const filePath = join(projectRoot, CLAUDE_RULES_REL);
  const body = buildBody(variant);
  if (!existsSync(filePath)) {
    mkdirSync(dirname(filePath), { recursive: true });
    writeFileSync(filePath, body);
    return 'created';
  }
  const current = readFileSync(filePath, 'utf8');
  if (current === body) return 'unchanged';
  // If the existing file is sweet-search-managed (sentinel present), rewrite
  // it. If a user wrote their own file at this path, leave it alone — they
  // can opt out by removing the sentinel-tagged version manually.
  if (!isOwned(current)) {
    return 'preserved-user-file';
  }
  writeFileSync(filePath, body);
  return 'updated';
}

/**
 * Remove `.claude/rules/sweet-search.md` if it carries a current or legacy
 * sweet-search sentinel.
 *
 * @returns 'removed' | 'not-found' | 'preserved-user-file' | 'dry-run'
 */
export function removeClaudeRules({ projectRoot, dryRun = false } = {}) {
  if (!projectRoot) throw new TypeError('remove-claude-rules: projectRoot is required');
  const filePath = join(projectRoot, CLAUDE_RULES_REL);
  if (!existsSync(filePath)) return 'not-found';
  const text = readFileSync(filePath, 'utf8');
  if (!isOwned(text)) return 'preserved-user-file';
  if (dryRun) return 'dry-run';
  unlinkSync(filePath);
  try { rmdirSync(dirname(filePath)); } catch { /* preserve non-empty rules directory */ }
  return 'removed';
}

// Exposed for tests.
export const _internal = { SENTINEL, LEGACY_SENTINEL, buildBody, isOwned };
