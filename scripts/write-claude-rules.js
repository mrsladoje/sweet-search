/**
 * Claude Code's sweet-search policy file: the unscoped project rule
 * `.claude/rules/sweet-search.md`.
 *
 * Two layouts (since "V1b", 2026-10-01, the first release after 2.8.2):
 *   full     the file carries the whole shipped policy. Used whenever the
 *            sweet-search lean harness is NOT the active main agent
 *            (--no-lean-harness, --no-cli, a user-selected main agent, a
 *            user-authored agent file).
 *   pointer  the layout while the lean harness is active: the policy rides
 *            in the main agent file (`.claude/agents/sweet-search.md`, i.e. the
 *            system prompt), and this file carries only CLAUDE_RULES_POINTER.
 *            Claude Code injects rules files into the FIRST USER MESSAGE,
 *            after the prompt-cache marker, so the ~1.4k policy tokens were
 *            re-written to the cache in every session; in the system prompt
 *            they are a cache read. The pointer keeps a short tool-choice
 *            reminder in the first user message (without it the share of
 *            ss-* calls fell from 0.53 to 0.32 on the task bench).
 * The 2.8.2 layout (full file under the lean harness) and the `none` layout
 * (no rules file) were bench arms of the SS_VARIANT_CC_RULES_IN_PROMPT switch,
 * deleted on 2026-10-03; old rows are reproduced from their git commit.
 *
 * Claude Code auto-loads unscoped `.claude/rules/*.md` files at launch with
 * the same instruction priority as `.claude/CLAUDE.md`; no CLAUDE.md import is
 * required. Keeping the policy here lets `sweet-search init` leave a project's
 * CLAUDE.md completely untouched.
 *
 * Apart from the ownership comment (which Claude strips before injection), the
 * file is the selected shipped policy body verbatim. There is no second,
 * hand-authored Claude-specific decision tree that can contradict it.
 */

import {
  existsSync,
  mkdirSync,
  readFileSync,
  rmdirSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { getPolicyBody } from './inject-agent-instructions.js';

export const CLAUDE_RULES_REL = '.claude/rules/sweet-search.md';

// The pointer file body (layout `pointer`). Change it only together with a new benchmark run.
export const CLAUDE_RULES_POINTER = [
  '# Sweet-search',
  'Use the `ss-*` tools (`ss-search`, `ss-grep`, `ss-read`, `ss-find`, `ss-semantic`, `ss-trace`) for all code search and navigation, as the sweet-search rules in your system prompt describe. Use raw `grep`/`cat` or the native reader only for a file edited seconds ago.',
].join('\n');

// Block-level HTML comments are removed before Claude injects project rules,
// so ownership metadata consumes no prompt tokens and does not alter M±.
const SENTINEL = '<!-- generated by `sweet-search init`; removed by `sweet-search uninstall` -->';
const LEGACY_SENTINEL =
  '<!-- generated by `sweet-search init`; edit `AGENTS.md` for the canonical policy -->';

// The pointer layout also names the project's auto-memory directory (from the lean harness), so the
// main agent file can stay the same in every project (a shared prompt-cache entry).
export const claudeRulesMemoryLine = (memoryDir) => `Your file-based memory directory for this project is \`${memoryDir}\`.`;

function buildBody(variant = 'cli', layout = 'full', env = process.env, memoryDir = null) {
  if (layout === 'pointer') return `${SENTINEL}\n${CLAUDE_RULES_POINTER}\n${memoryDir ? `${claudeRulesMemoryLine(memoryDir)}\n` : ''}`;
  if (layout !== 'full') throw new TypeError(`write-claude-rules: unknown layout ${layout}`);
  return `${SENTINEL}\n${getPolicyBody(variant, env).trimEnd()}\n`;
}

function isOwned(text) {
  return text.includes(SENTINEL) || text.includes(LEGACY_SENTINEL);
}

/**
 * Write `.claude/rules/sweet-search.md`. Idempotent: re-running with
 * unchanged content is a no-op (no mtime bump). `env` selects the rules text
 * (SS_VARIANT_RULES_FILE, inject-agent-instructions.js). `layout`: 'full' (the whole
 * policy, the default) or 'pointer' (CLAUDE_RULES_POINTER; only when the
 * active main agent file carries the policy). `memoryDir` (pointer layout only): the
 * lean harness's `memoryDir`, written as one line. Switching layouts rewrites a
 * sentinel-owned file in place; a user-authored file is never touched.
 *
 * @returns 'created' | 'updated' | 'unchanged' | 'preserved-user-file'
 */
export function writeClaudeRules({ projectRoot, variant = 'cli', layout = 'full', env = process.env, memoryDir = null } = {}) {
  if (!projectRoot) throw new TypeError('write-claude-rules: projectRoot is required');
  const filePath = join(projectRoot, CLAUDE_RULES_REL);
  const body = buildBody(variant, layout, env, memoryDir);
  if (!existsSync(filePath)) {
    mkdirSync(dirname(filePath), { recursive: true });
    writeFileSync(filePath, body);
    return 'created';
  }
  const current = readFileSync(filePath, 'utf8');
  if (current === body) return 'unchanged';
  // If the existing file is sweet-search-managed (sentinel present), rewrite
  // it. If a user wrote their own file at this path, leave it alone — they
  // can opt out by removing the sentinel-tagged version manually.
  if (!isOwned(current)) {
    return 'preserved-user-file';
  }
  writeFileSync(filePath, body);
  return 'updated';
}

/**
 * Remove `.claude/rules/sweet-search.md` if it carries a current or legacy
 * sweet-search sentinel.
 *
 * @returns 'removed' | 'not-found' | 'preserved-user-file' | 'dry-run'
 */
export function removeClaudeRules({ projectRoot, dryRun = false } = {}) {
  if (!projectRoot) throw new TypeError('remove-claude-rules: projectRoot is required');
  const filePath = join(projectRoot, CLAUDE_RULES_REL);
  if (!existsSync(filePath)) return 'not-found';
  const text = readFileSync(filePath, 'utf8');
  if (!isOwned(text)) return 'preserved-user-file';
  if (dryRun) return 'dry-run';
  unlinkSync(filePath);
  try { rmdirSync(dirname(filePath)); } catch { /* preserve non-empty rules directory */ }
  return 'removed';
}

// Exposed for tests.
export const _internal = { SENTINEL, LEGACY_SENTINEL, buildBody, isOwned };
