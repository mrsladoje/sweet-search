/**
 * File helpers shared by the `sweet-search init` / `uninstall` installers.
 */

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

export const OWNERSHIP_SENTINEL = '<!-- generated by `sweet-search init`; removed by `sweet-search uninstall` -->';

const sha = s => createHash('sha256').update(s).digest('hex');

/**
 * Create parent directories, then write `text` through `<path>.sweet-search.tmp` and rename it
 * into place.
 */
export function writeAtomic(path, text) {
  mkdirSync(dirname(path), { recursive: true });
  const tmp = `${path}.sweet-search.tmp`;
  writeFileSync(tmp, text, 'utf8');
  renameSync(tmp, path);
}

/** Write `text` through `<path>.tmp` and rename it into place. The parent directory must exist. */
export function writeViaTmp(path, text) {
  const tmp = path + '.tmp';
  writeFileSync(tmp, text, 'utf8');
  renameSync(tmp, path);
}

/**
 * A file is ours when the manifest recorded the hash of what we wrote and the file still
 * has that content. A file that exists with any other content is the user's.
 * Returns 'absent' | 'ours' | 'user'.
 */
export function fileState(projectRoot, rel, manifest) {
  const path = join(projectRoot, rel);
  if (!existsSync(path)) return 'absent';
  const recorded = manifest?.files?.[rel];
  return recorded && sha(readFileSync(path, 'utf8')) === recorded ? 'ours' : 'user';
}

/** Walk up from `cwd` to the first directory with `.git` or `package.json`; `cwd` when none. */
export function detectProjectRoot(cwd = process.cwd()) {
  let dir = cwd;
  while (true) {
    if (existsSync(join(dir, '.git'))) return dir;
    if (existsSync(join(dir, 'package.json'))) return dir;
    const parent = dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  return cwd;
}
