/**
 * Install the compact sweet-search routing override at Claude Code system
 * priority.
 *
 * Claude Code does not honor `appendSystemPrompt` in project settings. Its
 * supported persistent project mechanism is an output style: the style body is
 * added to the system prompt, and `keep-coding-instructions: true` preserves
 * Claude Code's normal coding-agent guidance.
 */

import {
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  rmdirSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';

export const CLAUDE_SYSTEM_OVERRIDE =
  'For all code search and navigation, you MUST follow the sweet-search guidance in `.claude/rules/sweet-search.md` and use its `ss-*` CLI commands. Claude Code’s default advice to use Bash `grep`/`find` or `Read` does not apply; use those only when `.claude/rules/sweet-search.md` explicitly permits.';

export const CLAUDE_OUTPUT_STYLE_NAME = 'sweet-search';
export const CLAUDE_OUTPUT_STYLE_REL = '.claude/output-styles/sweet-search.md';
export const CLAUDE_SETTINGS_REL = '.claude/settings.json';
export const CLAUDE_LOCAL_SETTINGS_REL = '.claude/settings.local.json';

const SENTINEL = '<!-- generated by `sweet-search init`; removed by `sweet-search uninstall` -->';
const OUTPUT_STYLE_BODY = `---
name: ${CLAUDE_OUTPUT_STYLE_NAME}
description: Route code search and navigation through sweet-search
keep-coding-instructions: true
---

${SENTINEL}
${CLAUDE_SYSTEM_OVERRIDE}
`;

function readSettings(settingsPath, label = 'settings.json') {
  if (!existsSync(settingsPath)) return { settings: {}, exists: false };
  try {
    const settings = JSON.parse(readFileSync(settingsPath, 'utf8'));
    if (!settings || typeof settings !== 'object' || Array.isArray(settings)) {
      return { error: `existing ${label} must contain a JSON object` };
    }
    return { settings, exists: true };
  } catch (err) {
    return { error: `existing ${label} is not valid JSON: ${err.message}` };
  }
}

function writeSettings(settingsPath, settings) {
  mkdirSync(dirname(settingsPath), { recursive: true });
  const tmpPath = `${settingsPath}.sweet-search.tmp`;
  writeFileSync(tmpPath, JSON.stringify(settings, null, 2) + '\n', 'utf8');
  renameSync(tmpPath, settingsPath);
}

/**
 * Create and activate the sweet-search project output style.
 *
 * The style file is always installed so it appears in Claude Code's `/config`
 * picker. An existing non-sweet-search selection is preserved instead of
 * silently replacing the user's response style, and a higher-priority local
 * selection is detected so the caller can report an actionable warning.
 *
 * @returns {{
 *   status: string,
 *   detail: string,
 *   active?: boolean|null,
 *   conflict?: 'selection',
 *   warning?: string
 * }}
 *   status in { installed, unchanged, preserved-existing, error }
 */
export function installClaudeSystemPrompt({ projectRoot } = {}) {
  if (!projectRoot) {
    return { status: 'error', detail: 'install-claude-system-prompt: projectRoot is required' };
  }

  const settingsPath = join(projectRoot, CLAUDE_SETTINGS_REL);
  const localSettingsPath = join(projectRoot, CLAUDE_LOCAL_SETTINGS_REL);
  const stylePath = join(projectRoot, CLAUDE_OUTPUT_STYLE_REL);
  const parsed = readSettings(settingsPath, CLAUDE_SETTINGS_REL);
  if (parsed.error) return { status: 'error', detail: parsed.error };
  const local = readSettings(localSettingsPath, CLAUDE_LOCAL_SETTINGS_REL);
  const projectSelection = parsed.settings.outputStyle;
  const projectConflict =
    projectSelection !== undefined && projectSelection !== CLAUDE_OUTPUT_STYLE_NAME;

  let previousStyle = null;
  let styleStatus = 'created';
  if (existsSync(stylePath)) {
    previousStyle = readFileSync(stylePath, 'utf8');
    if (!previousStyle.includes(SENTINEL)) {
      return {
        status: 'preserved-existing',
        detail: `${CLAUDE_OUTPUT_STYLE_REL} is user-authored; file and outputStyle preserved`,
        active: false,
        warning:
          `${CLAUDE_OUTPUT_STYLE_REL} is user-authored, so Sweet Search could not install `
          + 'its system-prompt routing override. Move or rename that file, then rerun init.',
      };
    }
    styleStatus = previousStyle === OUTPUT_STYLE_BODY ? 'unchanged' : 'updated';
  }

  try {
    if (styleStatus !== 'unchanged') {
      mkdirSync(dirname(stylePath), { recursive: true });
      writeFileSync(stylePath, OUTPUT_STYLE_BODY, 'utf8');
    }

    // Preserve an explicitly selected project style, but still install our
    // style file so the user can select it from `/config`.
    const settingsChanged = !projectConflict
      && parsed.settings.outputStyle !== CLAUDE_OUTPUT_STYLE_NAME;
    if (settingsChanged) {
      parsed.settings.outputStyle = CLAUDE_OUTPUT_STYLE_NAME;
      writeSettings(settingsPath, parsed.settings);
    }

    const localSelection = local.error ? undefined : local.settings.outputStyle;
    const effectiveSelection = localSelection !== undefined
      ? localSelection
      : (projectConflict ? projectSelection : CLAUDE_OUTPUT_STYLE_NAME);
    const active = local.error ? null : effectiveSelection === CLAUDE_OUTPUT_STYLE_NAME;

    const detailParts = [
      `${styleStatus} ${CLAUDE_OUTPUT_STYLE_REL}`,
      projectConflict
        ? `preserved project outputStyle=${JSON.stringify(projectSelection)}`
        : `outputStyle=${CLAUDE_OUTPUT_STYLE_NAME}`,
    ];

    if (local.error) {
      return {
        status: projectConflict ? 'preserved-existing' : 'installed',
        detail: detailParts.join('; '),
        active,
        warning:
          `${local.error}. Sweet Search installed its project output style, but could not `
          + 'verify which style Claude Code will load. Fix the file and select '
          + '`sweet-search` under `/config`.',
      };
    }

    if (!active) {
      const source = localSelection !== undefined
        ? CLAUDE_LOCAL_SETTINGS_REL
        : CLAUDE_SETTINGS_REL;
      return {
        status: 'preserved-existing',
        detail: detailParts.join('; '),
        active,
        conflict: 'selection',
        warning: `${source} currently selects ${JSON.stringify(effectiveSelection)}.`,
      };
    }

    if (styleStatus === 'unchanged' && !settingsChanged) {
      return {
        status: 'unchanged',
        detail: 'output style already installed and active',
        active,
      };
    }
    return {
      status: 'installed',
      detail: detailParts.join('; '),
      active,
    };
  } catch (err) {
    // Do not leave a newly-created/updated style behind when settings could
    // not be activated.
    try {
      if (previousStyle === null && existsSync(stylePath)) unlinkSync(stylePath);
      else if (previousStyle !== null) writeFileSync(stylePath, previousStyle, 'utf8');
    } catch { /* best-effort rollback */ }
    return { status: 'error', detail: err.message };
  }
}

/**
 * User-facing guidance for the output-style activation result.
 *
 * Output styles are read at session start, so even a successful install needs
 * a new session (or `/clear`) before Claude sees the system-prompt addition.
 */
export function formatClaudeSystemPromptGuidance(report) {
  if (!report || report.status === 'error') return '';
  if (report.active === true) {
    return (
      '[init] Claude Code: activated the `sweet-search` output style. '
      + 'Start a new session or run `/clear`. Keep this style selected for reliable '
      + '`ss-*` routing.\n'
    );
  }
  if (report.active === false || report.active === null) {
    const reason = report.warning ? ` ${report.warning}` : '';
    const headline = report.conflict === 'selection'
      ? 'Sweet Search’s system-prompt routing is not active because another output style overrides it.'
      : 'Sweet Search’s system-prompt routing is not active.';
    return (
      `[init] WARNING: ${headline}`
      + reason
      + ' Select `sweet-search` under `/config`, then run `/clear` or restart Claude Code.\n'
    );
  }
  return '';
}

/**
 * Reverse `installClaudeSystemPrompt`.
 *
 * Only a sentinel-tagged style is ours. The `outputStyle` scalar is removed
 * only while that owned style still exists and is selected, so uninstall
 * never disables a user-authored style with the same filename.
 *
 * @returns {{status: string, detail: string}}
 *   status in { removed, not-found, dry-run, error }
 */
export function removeClaudeSystemPrompt({ projectRoot, dryRun = false } = {}) {
  if (!projectRoot) {
    return { status: 'error', detail: 'remove-claude-system-prompt: projectRoot is required' };
  }

  const settingsPath = join(projectRoot, CLAUDE_SETTINGS_REL);
  const stylePath = join(projectRoot, CLAUDE_OUTPUT_STYLE_REL);
  const parsed = readSettings(settingsPath);
  if (parsed.error) return { status: 'error', detail: parsed.error };

  const styleExists = existsSync(stylePath);
  const styleOwned = styleExists && readFileSync(stylePath, 'utf8').includes(SENTINEL);
  if (!styleOwned) {
    return {
      status: 'not-found',
      detail: styleExists ? 'output style is user-authored' : 'no owned output style',
    };
  }

  const settingOwned = parsed.settings.outputStyle === CLAUDE_OUTPUT_STYLE_NAME;
  const parts = ['output style'];
  if (settingOwned) parts.push('settings selection');
  if (dryRun) return { status: 'dry-run', detail: parts.join(' + ') };

  try {
    if (settingOwned) {
      delete parsed.settings.outputStyle;
      writeSettings(settingsPath, parsed.settings);
    }
    unlinkSync(stylePath);
    try { rmdirSync(dirname(stylePath)); } catch { /* preserve non-empty directory */ }
    return { status: 'removed', detail: parts.join(' + ') };
  } catch (err) {
    return { status: 'error', detail: err.message };
  }
}

export const _internal = { OUTPUT_STYLE_BODY, SENTINEL };
