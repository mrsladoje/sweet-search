#!/usr/bin/env node
// Regenerates THIRD_PARTY_LICENSES from the Rust crates that ship as binaries.
// Needs cargo-about: cargo install cargo-about --locked --features cli
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const CRATES = [
  'crates/sweet-search-native',
  'crates/sweet-search-cli',
  'crates/wasm-maxsim',
  'crates/wasm-router',
  'native/bg-priority',
  'native/mem-pressure',
];
const OWN = new Set(['sweet-search-native', 'sweet-search-cli', 'maxsim-wasm', 'query_router_wasm', 'bg-priority', 'mem-pressure']);

// Group by license text so identical texts appear once.
const byText = new Map();
for (const crate of CRATES) {
  const out = execFileSync('cargo', [
    'about', 'generate', '--format', 'json',
    '-c', join(root, 'scripts/licenses/about.toml'),
    '--manifest-path', join(root, crate, 'Cargo.toml'),
  ], { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] });
  for (const lic of JSON.parse(out).licenses) {
    const users = lic.used_by.map((u) => u.crate).filter((c) => !OWN.has(c.name));
    if (users.length === 0) continue;
    const entry = byText.get(lic.text) ?? { id: lic.id, name: lic.name, crates: new Map() };
    for (const c of users) entry.crates.set(`${c.name} ${c.version}`, true);
    byText.set(lic.text, entry);
  }
}

const sections = [...byText.entries()]
  .sort(([, a], [, b]) => a.id.localeCompare(b.id))
  .map(([text, e]) => [
    '='.repeat(79),
    `${e.name} (${e.id})`,
    'Used by:',
    ...[...e.crates.keys()].sort().map((k) => `  - ${k}`),
    '-'.repeat(79),
    text.trim(),
    '',
  ].join('\n'));

writeFileSync(join(root, 'THIRD_PARTY_LICENSES'), [
  'Third-party licenses for Rust crates compiled into the Sweet Search',
  'native binaries and WebAssembly modules.',
  '',
  'Generated by scripts/licenses/generate-third-party-licenses.mjs. Do not edit.',
  '',
  ...sections,
].join('\n'));
console.log(`THIRD_PARTY_LICENSES: ${byText.size} license texts`);
